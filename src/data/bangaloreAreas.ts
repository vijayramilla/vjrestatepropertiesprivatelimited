/** Canonical deduped area list. First entry wins on duplicate names. */
const seen = new Set<string>();
export const BANGALORE_AREAS_FULL: BangaloreArea[] = RAW_AREAS.filter((a) => {
  const key = a.n.toLowerCase();
  if (seen.has(key)) return false;
  seen.add(key);
  return true;
}).map((a) => ({ name: a.n, zone: a.z }));

