/**
 * Fuzzy-search the full area directory: exact → prefix → word-start →
 * compact ("hsr" → HSR Layout) → substring. Compact queries like
 * "kadubasanahalli" or "ecity" match the right entry.
 */
export function searchBangaloreAreas(query: string, limit = 60): BangaloreArea[] {
  const q = query.trim().toLowerCase();
  if (!q) return BANGALORE_AREAS_FULL.slice(0, limit);

  const compactQ = q.replace(/[\s./-]+/g, '');

  return BANGALORE_AREAS_FULL.map((a) => {
    const lower = a.name.toLowerCase();
    const compact = lower.replace(/[\s./-]+/g, '');
    const words = lower.split(/[\s,-]+/).filter(Boolean);
    let score = 0;

    if (lower === q) score = 100;
    else if (lower.startsWith(q)) score = 95;
    else if (words.some((w) => w.startsWith(q))) score = 85;
    else if (compact.startsWith(compactQ)) score = 80;
    else if (compact.includes(compactQ)) score = 70;
    else if (lower.includes(q)) score = 60;

    return { a, score };
  })
    .filter(({ score }) => score > 0)
    .sort((x, y) => y.score - x.score || x.a.name.localeCompare(y.a.name))
    .slice(0, limit)
    .map(({ a }) => a);
}
